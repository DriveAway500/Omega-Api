"""
Read-only access to the KEV index produced by build_kev_index.py.

This module never writes or builds anything. It only loads the JSON
index files already generated by the standalone builder script, diffs
them against one another, and searches them. It exists solely so the
API routes have data to read — nothing here is a CLI or triggers a
rebuild.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Iterable

BASE_DIR = Path(__file__).resolve().parent

# Must point at the same OUTPUT_DIR the builder script writes to.
OUTPUT_DIR = Path(os.environ.get("KEV_OUTPUT_DIR", BASE_DIR / "../kev_data"))

INDEX_PATH = OUTPUT_DIR / "../kev_data/index/kev_index.json"
PREVIOUS_INDEX_PATH = OUTPUT_DIR / "../kev_data/index/kev_index.previous.json"

SEARCHABLE_FIELDS = (
    "cveID",
    "vendorProject",
    "product",
    "vulnerabilityName",
    "shortDescription",
    "cwes",
)

_EMPTY_INDEX: dict[str, Any] = {
    "generated_at": None,
    "source_file": None,
    "count": 0,
    "entries": {},
}


def load_index(path: Path = INDEX_PATH) -> dict[str, Any]:
    """Load an index JSON file. Returns an empty-but-valid index if it
    hasn't been built yet, so callers never have to special-case None."""
    if not path.exists():
        return dict(_EMPTY_INDEX)
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def diff_indexes(old_index: dict[str, Any], new_index: dict[str, Any]) -> dict[str, Any]:
    """Compare two already-loaded indexes and report added/removed/modified entries."""
    old_entries: dict[str, dict] = old_index.get("entries", {})
    new_entries: dict[str, dict] = new_index.get("entries", {})

    old_ids = set(old_entries)
    new_ids = set(new_entries)

    added_ids = new_ids - old_ids
    removed_ids = old_ids - new_ids
    common_ids = old_ids & new_ids

    modified_ids = sorted(
        cve_id for cve_id in common_ids if old_entries[cve_id] != new_entries[cve_id]
    )

    return {
        "old_generated_at": old_index.get("generated_at"),
        "new_generated_at": new_index.get("generated_at"),
        "added": [new_entries[i] for i in sorted(added_ids)],
        "removed": [old_entries[i] for i in sorted(removed_ids)],
        "modified": [
            {"cveID": i, "before": old_entries[i], "after": new_entries[i]}
            for i in modified_ids
        ],
        "added_count": len(added_ids),
        "removed_count": len(removed_ids),
        "modified_count": len(modified_ids),
    }


def diff_against_previous(
    index_path: Path = INDEX_PATH, previous_index_path: Path = PREVIOUS_INDEX_PATH
) -> dict[str, Any]:
    """Diff the current index against the one from the previous builder run."""
    current = load_index(index_path)
    previous = load_index(previous_index_path)
    return diff_indexes(previous, current)


def search(
    index: dict[str, Any],
    query: str,
    fields: Iterable[str] | None = None,
    limit: int = 50,
    offset: int = 0,
) -> dict[str, Any]:
    """
    Case-insensitive substring search across `fields` (defaults to
    SEARCHABLE_FIELDS) of every indexed row. Results are sorted by
    dateAdded, most recent first.
    """
    fields = tuple(fields) if fields else SEARCHABLE_FIELDS
    q = query.strip().lower()

    matches = []
    for row in index.get("entries", {}).values():
        haystack = " ".join(str(row.get(f, "")) for f in fields).lower()
        if q in haystack:
            matches.append(row)

    matches.sort(key=lambda r: r.get("dateAdded", ""), reverse=True)
    total = len(matches)
    page = matches[offset : offset + limit]

    return {"total": total, "limit": limit, "offset": offset, "results": page}


def get_by_id(index: dict[str, Any], cve_id: str) -> dict[str, Any] | None:
    return index.get("entries", {}).get(cve_id.strip())